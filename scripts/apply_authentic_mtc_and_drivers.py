def get_real_driver(truck_no, trip_id):
    trk = (truck_no or '').strip().upper()
    if trk in truck_to_driver:
        return truck_to_driver[trk]
    # Deterministic assignment based on truck number or trip id
    seed = sum(ord(c) for c in (trk or str(trip_id)))
    return driver_names[seed % len(driver_names)]

